// Beat 4: hosted sandbox. Start a session, borrow on a weekday, Jump to Saturday, refused borrow, repay works.
import { take } from "../rig.mjs"
const shot = (page, n) => page.screenshot({ path: `film/look/wk-${n}.png` }).catch(() => {})
await take("weekend", async f => {
  const { page } = f
  await page.goto("https://intatto.larinova.com/sandbox")
  const start = page.getByRole("button", { name: "Start a session" })
  await start.waitFor({ timeout: 90000 }); await page.waitForFunction(() => [...document.querySelectorAll("button")].some(b => b.textContent.trim() === "Start a session" && !b.disabled), null, { timeout: 120000 })
  await f.glide(720, 450, 10)
  f.mark("sandbox-loaded"); await f.wait(2500)
  f.mark("start-click"); await f.click(start, 900)
  await page.getByTestId("sandbox-session").waitFor({ timeout: 240000 })
  await page.getByTestId("burner-connection").filter({ hasText: "Connected" }).waitFor({ timeout: 120000 })
  f.mark("session-ready"); await f.wait(2500); await shot(page, "1-session")
  await f.point(page.getByTestId("sandbox-session"), 900, 0.3, 0.35); await f.wait(2000)
  f.mark("to-borrow"); await f.click(page.getByRole("link", { name: "Borrow", exact: true }).first(), 900)
  await page.getByTestId("borrow-screen").waitFor({ timeout: 120000 })
  await page.getByTestId("deposit-borrow-form").getByText("Can borrow").waitFor({ timeout: 120000 }).catch(() => {})
  f.mark("borrow-loaded"); await f.wait(1500)
  await f.type(page.locator("#borrow-collateral"), "4", 180); await f.wait(900)
  f.mark("loan-typed"); await f.type(page.locator("#borrow-loan"), "300", 180); await f.wait(2200); await shot(page, "2-preview")
  const cta = page.getByTestId("deposit-borrow-form").locator('[data-slot="form-cta"] button')
  await page.waitForFunction(() => document.querySelector('[data-testid="deposit-borrow-form"] [data-slot="form-cta"] button')?.textContent.trim() === "Review", null, { timeout: 60000 })
  f.mark("review"); await f.click(cta, 800)
  const review = page.getByTestId("borrow-review")
  await review.waitFor({ timeout: 60000 }); await f.wait(1200)
  f.mark("approve"); await f.click(review.getByRole("button", { name: "Approve NVDAx" }), 800)
  await page.locator("[data-sonner-toast]").filter({ hasText: "NVDAx approved" }).waitFor({ timeout: 90000 }); await f.wait(800)
  f.mark("deposit"); await f.click(review.getByRole("button", { name: /^Deposit / }), 800)
  await review.getByTestId("review-done-step").filter({ hasText: "Deposited" }).waitFor({ timeout: 90000 }); await f.wait(800)
  f.mark("borrow"); await f.click(review.getByRole("button", { name: /^Borrow / }), 800)
  await review.getByTestId("review-finished").waitFor({ timeout: 90000 })
  f.mark("borrowed"); await f.wait(2500); await shot(page, "3-borrowed")
  await f.click(review.getByRole("button", { name: "Back to the form" }), 800); await f.wait(1500)
  await f.point(page.getByTestId("position-panel"), 900, 0.3, 0.3); await f.wait(2000)
  f.mark("to-sandbox"); await f.click(page.getByRole("link", { name: "Sandbox", exact: true }).first(), 900)
  const sat = page.getByRole("button", { name: "Jump to Saturday" })
  await sat.waitFor({ timeout: 60000 }); await f.wait(1500)
  f.mark("saturday-click"); await f.click(sat, 900)
  await page.getByTestId("action-result").filter({ hasText: "Jump to Saturday: done" }).waitFor({ timeout: 180000 })
  f.mark("saturday-done"); await f.wait(3000); await shot(page, "4-saturday")
  f.mark("to-borrow-2"); await f.click(page.getByRole("link", { name: "Borrow", exact: true }).first(), 900)
  await page.getByTestId("borrow-screen").waitFor({ timeout: 60000 }); await f.wait(2500)
  await f.point(page.getByTestId("session-max-ltv").first(), 800); await f.wait(1800)
  f.mark("try-more"); await f.type(page.locator("#borrow-loan"), "10", 200)
  await page.waitForFunction(() => /Refused/.test(document.querySelector('[data-testid="deposit-borrow-form"] [data-slot="form-cta"] button')?.textContent ?? ""), null, { timeout: 60000 })
  f.mark("refused"); await f.point(cta, 900); await f.wait(3500); await shot(page, "5-refused")
  f.mark("repay-tab"); await f.click(page.getByRole("tab", { name: "Repay & withdraw" }), 900); await f.wait(1200)
  await f.type(page.locator("#repay-amount"), "100", 180); await f.wait(1500)
  const rcta = page.getByTestId("repay-withdraw-form").locator('[data-slot="form-cta"] button')
  await page.waitForFunction(() => document.querySelector('[data-testid="repay-withdraw-form"] [data-slot="form-cta"] button')?.textContent.trim() === "Review", null, { timeout: 60000 })
  f.mark("repay-review"); await f.click(rcta, 800)
  const rr = page.getByTestId("repay-review"); await rr.waitFor({ timeout: 60000 }); await f.wait(1000)
  const approve = rr.getByRole("button", { name: "Approve USDG" })
  if (await approve.isVisible({ timeout: 8000 }).catch(() => false)) { f.mark("approve-usdg"); await f.click(approve, 800); await page.locator("[data-sonner-toast]").filter({ hasText: "USDG approved" }).waitFor({ timeout: 90000 }).catch(() => {}); await f.wait(800) }
  f.mark("repay"); await f.click(rr.getByRole("button", { name: /^Repay / }), 800)
  await rr.getByTestId("review-finished").waitFor({ timeout: 90000 })
  f.mark("repaid"); await f.wait(3500); await shot(page, "6-repaid")
  f.mark("end")
})
