// Beats 6-7: the January 2025 replay (CFD data) liquidates nobody; the synthetic 45% gap shows slices, reserve and deficit.
import { take } from "../rig.mjs"
const shot = (page, n) => page.screenshot({ path: `film/look/rp-${n}.png` }).catch(() => {})
await take("replays", async f => {
  const { page } = f
  const nav = name => page.locator("header, nav").getByRole("link", { name, exact: true }).first()
  const riskView = async name => { const v = page.locator('nav[aria-label="Risk analyses"]').getByText(name, { exact: true }).first(); await f.click(v, 800); await f.wait(1800) }
  await page.goto("https://intatto.larinova.com/sandbox")
  const start = page.getByRole("button", { name: "Start a session" })
  await page.waitForFunction(() => [...document.querySelectorAll("button")].some(b => b.textContent.trim() === "Start a session" && !b.disabled), null, { timeout: 120000 })
  await f.glide(720, 450, 10)
  f.mark("sandbox-loaded"); await f.wait(1000)
  f.mark("start-click"); await f.click(start, 700)
  await page.getByTestId("sandbox-session").waitFor({ timeout: 240000 })
  await page.getByTestId("burner-connection").filter({ hasText: "Connected" }).waitFor({ timeout: 120000 })
  f.mark("session-ready"); await f.wait(1500)
  const jan = page.getByTestId("scenario-gap-2025-01")
  f.mark("scroll-scenarios"); await f.scrollToEl(jan, 110, 1600); await f.wait(1200)
  await f.point(jan, 900, 0.3, 0.3); await f.wait(2500); await shot(page, "1-scenarios")
  f.mark("jan-click"); await f.click(jan.getByRole("button", { name: "Replay the January 2025 gap" }), 800)
  await page.getByTestId("action-result").filter({ hasText: "Replay the January 2025 gap: done" }).waitFor({ timeout: 240000 })
  f.mark("jan-done"); await f.wait(2500); await shot(page, "2-jan-done")
  const ledger = page.getByTestId("ledger-row").first()
  f.mark("ledger"); await f.scrollToEl(ledger, 220, 1400); await f.wait(3000); await shot(page, "3-ledger")
  f.mark("to-risk"); await f.click(nav("Risk"), 900)
  await page.getByTestId("risk-console").waitFor({ timeout: 90000 }); await f.wait(3000); await shot(page, "4-risk-summary")
  f.mark("risk-loans"); await riskView("Loans near liquidation"); await f.wait(1200)
  await f.point(page.getByText(/^0x0000/).first(), 800); await f.wait(600); await f.glide(560 + 280, (await page.getByText(/^0x0000/).first().boundingBox()).y + 8, 900); await f.wait(2500); await shot(page, "5-risk-loans")
  f.mark("risk-liqs"); await riskView("Liquidations"); await f.wait(3000); await shot(page, "6-risk-liqs-jan")
  f.mark("to-sandbox"); await f.click(nav("Sandbox"), 900)
  const syn = page.getByTestId("scenario-synthetic-gap")
  await syn.waitFor({ timeout: 60000 }); await f.scrollToEl(syn, 110, 1400); await f.wait(1500)
  f.mark("syn-click"); await f.click(syn.getByRole("button", { name: "Run a synthetic 45% gap" }), 800)
  await page.getByTestId("action-result").filter({ hasText: "Run a synthetic 45% gap: done" }).waitFor({ timeout: 240000 })
  f.mark("syn-done"); await f.wait(2500); await shot(page, "7-syn-done")
  f.mark("to-risk-2"); await f.click(nav("Risk"), 900)
  await page.getByTestId("risk-console").waitFor({ timeout: 90000 }); await f.wait(2000)
  f.mark("risk-liqs-2"); await riskView("Liquidations"); await f.wait(3500); await shot(page, "8-risk-liqs-syn")
  f.mark("risk-deficit-tile"); await f.point(page.getByText("Lender deficit now").first(), 800); await f.wait(2500)
  f.mark("to-lend"); await f.click(nav("Lend"), 900)
  const primer = page.getByTestId("lend-primer")
  await primer.waitFor({ timeout: 90000 }); await f.wait(1500)
  f.mark("primer-lose"); await f.point(primer.getByText("Lenders can lose money.").first(), 900, 0.3); await f.wait(3500); await shot(page, "9-primer")
  f.mark("primer-close"); await f.click(primer.getByRole("button", { name: /close/i }).first(), 800); await f.wait(1500)
  await page.getByTestId("share-price").first().waitFor({ timeout: 60000 }).catch(() => {})
  f.mark("share-price"); await f.point(page.getByTestId("share-price").first(), 800); await f.wait(2500); await shot(page, "10-lend")
  const deficit = page.getByTestId("deficit-card").or(page.getByTestId("deficits-table")).first()
  f.mark("deficit"); await f.scrollToEl(deficit, 160, 1800); await f.wait(800); await f.point(deficit, 800, 0.4, 0.4); await f.wait(3500); await shot(page, "11-deficit")
  f.mark("end")
})
