import { chromium } from "@playwright/test"
const b = await chromium.launch()
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, timezoneId: "UTC" })
const p = await ctx.newPage()
await p.goto("https://www.oklink.com/x-layer/address/0xE6708CC6598F17611f9A468f9907052688459D0D")
await p.waitForTimeout(9000)
console.log(await p.evaluate(() => [...document.querySelectorAll("a")].map(a => a.textContent.trim() + " -> " + a.getAttribute("href")).filter(s => /0x[a-f0-9]{6}/i.test(s)).slice(0, 12).join("\n")))
const tx = p.locator("text=/0xa933/").first()
console.log("count", await p.locator("text=/0xa933/").count())
await tx.click({ timeout: 5000 }).catch(e => console.log("click fail"))
await p.waitForTimeout(10000)
await p.screenshot({ path: "film/look/oklink-tx2.png" })
console.log(p.url(), (await p.locator("body").innerText()).replace(/\n+/g, " | ").slice(0, 1000))
await b.close()
